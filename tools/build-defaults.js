// Maintenance tool (optional — NOT needed to deploy the site).
// Re-generates api/defaults.json from the defaults() / seedServices() / seedPosts() built into the
// site's JavaScript, so the PHP side (render.php, sitemap, llms.txt) has the same fallback content
// as the browser when the database is empty or missing a newer setting.
//
// Run after editing those defaults:   node tools/build-defaults.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');

// The component lives in assets/app.js (or, in older versions, inline in index.html).
const appJs = path.join(root, 'assets', 'app.js');
let code;
if (fs.existsSync(appJs)) code = fs.readFileSync(appJs, 'utf8');
else {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  code = [...html.matchAll(/<script(?![^>]*\b(?:src|type)=)[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]).join('\n;\n');
}

const store = {};
const ctx = {
  React: { Component: class { constructor(p) { this.props = p || {}; } setState() {} forceUpdate() {} }, createElement: () => null },
  ReactDOM: { createRoot: () => ({ render() {} }) },
  localStorage: { getItem: k => store[k] ?? null, setItem: (k, v) => { store[k] = String(v); }, removeItem: k => { delete store[k]; } },
  document: { getElementById: () => ({}), head: { querySelector: () => null, appendChild() {} }, createElement: () => ({ setAttribute() {} }), addEventListener() {}, documentElement: { classList: { add() {} } } },
  location: { pathname: '/', hash: '' }, history: { replaceState() {} }, navigator: {},
  fetch: () => new Promise(() => {}), setTimeout: () => 0, clearTimeout() {}, console,
};
ctx.window = ctx; ctx.addEventListener = () => {};
vm.createContext(ctx);
vm.runInContext(code + '\n;globalThis.__C = Component;', ctx, { filename: 'app.js' });

const inst = new ctx.__C({});
let n = 0; inst.uid = () => 'd' + (++n);            // deterministic ids => stable diffs
const d = inst.defaults();
delete d.adminPass;                                 // credentials never live in a public file
d._seedServices = inst.seedServices();
d._seedPosts = inst.seedPosts();
d._note = 'Generated by tools/build-defaults.js from the site JavaScript. Fallback content only — the live database always wins.';
fs.writeFileSync(path.join(root, 'api', 'defaults.json'), JSON.stringify(d, null, 1) + '\n');
console.log('api/defaults.json written:', Object.keys(d).length, 'top-level keys,', d.services.length, 'services +', d._seedServices.length, 'seed services,', d.blog.length, 'posts +', d._seedPosts.length, 'seed posts');
